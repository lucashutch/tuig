//! Terminal column widths and column-based truncation.
//!
//! The TypeScript app measures text with `Bun.stringWidth`. [`string_width`] reproduces its
//! results for text without ANSI escapes, so labels clip at the same column in both apps.
//! Per-character widths come from tables generated with Bun 1.4.3, because the Unicode data in
//! `unicode-width` differs from Bun's for Indic marks, Hangul jungseong and unassigned code points.
//! Emoji sequences use `unicode-width` and grapheme clusters. Thai U+0E33 next to U+200D or U+FE0F
//! is the only known difference.
//! The truncation helpers walk code points, not graphemes, like their TypeScript originals.

use unicode_segmentation::UnicodeSegmentation;
use unicode_width::UnicodeWidthStr;

/// Columns that `text` covers on a terminal row.
pub fn string_width(text: &str) -> usize {
    text.graphemes(true).map(grapheme_width).sum()
}

fn grapheme_width(grapheme: &str) -> usize {
    let mut chars = grapheme.chars();
    let (Some(first), Some(_)) = (chars.next(), chars.next()) else {
        return grapheme.chars().next().map_or(0, char_width);
    };
    let joined_emoji = |c: char| matches!(c, '\u{200D}' | '\u{FE0F}' | '\u{1F3FB}'..='\u{1F3FF}');
    if grapheme.contains('\u{20E3}')
        || is_regional_indicator(first)
        || (grapheme.chars().any(joined_emoji) && can_be_emoji(first))
    {
        return 2;
    }
    grapheme.chars().map(char_width).sum()
}

fn is_regional_indicator(c: char) -> bool {
    ('\u{1F1E6}'..='\u{1F1FF}').contains(&c)
}

/// True for characters that `Bun.stringWidth` widens to two columns inside an emoji sequence.
/// ASCII is excluded, so `1` followed by U+FE0F stays one column.
fn can_be_emoji(c: char) -> bool {
    if char_width(c) == 2 {
        return true;
    }
    !c.is_ascii() && UnicodeWidthStr::width(format!("{c}\u{FE0F}").as_str()) == 2
}

fn char_width(c: char) -> usize {
    let cp = c as u32;
    if in_ranges(ZERO_WIDTH, cp) {
        0
    } else if in_ranges(WIDE, cp) {
        2
    } else {
        1
    }
}

fn in_ranges(ranges: &[(u32, u32)], cp: u32) -> bool {
    ranges
        .binary_search_by(|&(start, end)| {
            if cp < start {
                std::cmp::Ordering::Greater
            } else if cp > end {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

/// Keeps each tree node on one terminal row while retaining both ends of long names.
pub fn fit_tree_label(label: &str, width: i64) -> String {
    if width <= 0 {
        return String::new();
    }
    let width = width as usize;
    if string_width(label) <= width {
        return label.to_string();
    }
    if width == 1 {
        return "…".to_string();
    }
    if width < 5 {
        return format!("{}…", take_columns(label, width - 1, false));
    }
    let tail = 2.max((((width - 1) as f64) * 0.4).floor() as usize);
    let head = width - tail - 1;
    format!(
        "{}…{}",
        take_columns(label, head, false),
        take_columns(label, tail, true)
    )
}

/// Takes whole code points from the start (or end) of `text` while they fit in `width` columns.
pub fn take_columns(text: &str, width: usize, from_end: bool) -> String {
    let mut taken: Vec<char> = Vec::new();
    let mut used = 0;
    let mut push = |c: char| {
        let columns = string_width(c.encode_utf8(&mut [0; 4]));
        if used + columns > width {
            return false;
        }
        taken.push(c);
        used += columns;
        true
    };
    if from_end {
        for c in text.chars().rev() {
            if !push(c) {
                break;
            }
        }
        taken.reverse();
    } else {
        for c in text.chars() {
            if !push(c) {
                break;
            }
        }
    }
    taken.into_iter().collect()
}

/// Pads or truncates `value` to exactly `width` columns, with an optional ellipsis.
pub fn fit_columns(value: &str, width: i64, ellipsis: bool) -> String {
    if width <= 0 {
        return String::new();
    }
    let width = width as usize;
    let value_width = string_width(value);
    if value_width <= width {
        return format!("{value}{}", " ".repeat(width - value_width));
    }
    let suffix = if ellipsis && width > 1 { "…" } else { "" };
    let target = width - string_width(suffix);
    let mut result = String::new();
    for c in value.chars() {
        let mut next = result.clone();
        next.push(c);
        if string_width(&next) > target {
            break;
        }
        result = next;
    }
    result.push_str(suffix);
    let padding = width.saturating_sub(string_width(&result));
    result + &" ".repeat(padding)
}

